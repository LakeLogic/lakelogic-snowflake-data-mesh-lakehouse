"""Structural checks for this generated LakeLogic project — run with `pytest tests/`.

Generated by LakeLogic Lakehouse Studio; edit it here or in Studio. These checks read the repo
as it is, so a hand edit that breaks the shape (a system with no job, a registry that no longer
resolves, a breach job that retries) fails here before it fails in production.
"""
import os
import re
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
#: The repository root: the contract tree is filed there, beside the platform folder.
REPO = Path(__file__).resolve().parents[3]
CONTRACTS = REPO / "contracts"
SYSTEM_FILES = sorted(CONTRACTS.rglob("_system.yaml"))
SYSTEMS = sorted((p.parent.parent.name, p.parent.name) for p in SYSTEM_FILES)
GROUPS = ('admin', 'data', 'monitor', 'privacy', 'test')
OPERATIONAL = {'_setup': 'admin', '_maintenance': 'admin', '_mesh_orchestrator': 'data', '_slo_checks': 'monitor', '_erasure': 'privacy', '_retention_check': 'privacy', '_synthetic_seed': 'test'}


def _ids(p):
    return f"{p.parent.parent.name}_{p.parent.name}"


def test_there_is_at_least_one_system():
    assert SYSTEMS, f"no _system.yaml under {CONTRACTS}"


@pytest.mark.parametrize("path", SYSTEM_FILES, ids=_ids)
def test_every_registered_contract_file_exists(path):
    reg = yaml.safe_load(path.read_text(encoding="utf-8"))
    assert (reg["domain"], reg["system"]) == (path.parent.parent.name, path.parent.name)
    for entry in reg.get("contracts") or []:
        assert (path.parent / entry["path"]).is_file(), entry["path"]


@pytest.mark.parametrize("path", SYSTEM_FILES, ids=_ids)
def test_registry_loads_and_resolves(path, monkeypatch):
    lakelogic = pytest.importorskip("lakelogic")  # noqa: F841 - the contract checks run without it
    from lakelogic.core.registry import DomainRegistry

    reg = yaml.safe_load(path.read_text(encoding="utf-8"))
    env = next(iter(reg.get("environments") or {"dev": {}}))
    for value in (reg.get("environments") or {}).get(env, {}).values():
        for var in re.findall(r"\$\{(\w+)\}", str(value)):
            monkeypatch.setenv(var, f"test_{var.lower()}")
    registry = DomainRegistry.from_yaml(str(path), environment=env, storage_mode="catalog")
    storage = registry.storage
    for field in ("domain_catalog", "quarantine_root", "landing_root", "log_root"):
        value = getattr(storage, field, None)
        assert value and "{" not in str(value), f"{field} left unresolved: {value}"
    declared = [c for c in registry.contracts if c.path]
    assert len(registry.get_active_contracts()) == len(declared), "a registered contract could not be loaded"



def _task_files():
    return {p.stem: (p.parent.name, p.read_text(encoding="utf-8")) for p in (ROOT / "tasks").glob("*/*.sql")}


def test_every_task_file_is_filed_in_its_group():
    for stem, (group, _sql) in _task_files().items():
        assert group == OPERATIONAL.get(stem, "data"), stem


def test_every_system_has_a_data_task_graph():
    files = _task_files()
    for domain, system in SYSTEMS:
        assert f"{domain}_{system}" in files, f"{domain}/{system} has no tasks/data file"


@pytest.mark.parametrize("stem", ["_slo_checks", "_retention_check"])
def test_breach_tasks_fail_on_breach_and_never_retry(stem):
    _group, sql = _task_files()[stem]
    assert "TASK_AUTO_RETRY_ATTEMPTS = 0" in sql
    assert "fail_on_breach=true" in sql


def test_setup_runs_every_generated_task_file_setup_first():
    setup = (ROOT / "sql" / "setup.sql").read_text(encoding="utf-8")
    ran = re.findall(r"/branches/\{\{BRANCH\}\}/(?:platform/snowflake/)?(tasks/[^ ]+\.sql)", setup)
    assert ran and ran[0] == "tasks/admin/_setup.sql"
    assert set(ran) == {p.relative_to(ROOT).as_posix() for p in (ROOT / "tasks").glob("*/*.sql")}
